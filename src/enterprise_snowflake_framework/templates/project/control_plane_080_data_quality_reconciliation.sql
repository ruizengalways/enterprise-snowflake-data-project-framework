CREATE OR REPLACE VIEW CONTROL.DATASET_HEALTH_V AS
WITH OPEN_INCIDENT AS (
    SELECT DATASET_ID, COUNT(*) AS OPEN_INCIDENT_COUNT
    FROM CONTROL.INCIDENT
    WHERE STATUS = 'OPEN'
    GROUP BY DATASET_ID
)
SELECT
    D.DATASET_ID,
    D.SOURCE_ID,
    D.DATASET_NAME,
    D.OWNER,
    D.CRITICALITY,
    D.PATTERN,
    D.ENABLED,
    UPPER(COALESCE(D.LIFECYCLE_STATUS, IFF(D.ENABLED, 'ACTIVE', 'PAUSED'))) AS LIFECYCLE_STATUS,
    D.ACTIVE_VERSION,
    D.CANDIDATE_VERSION,
    D.BRONZE_RELATION,
    D.PUBLISHED_SILVER_RELATION,
    H.EVALUATED_AT,
    H.INGESTION_STATUS,
    H.SILVER_STATUS,
    H.GOLD_STATUS,
    Q.DQ_STATUS,
    Q.RECONCILIATION_STATUS,
    Q.LAST_DQ_AT,
    Q.LAST_RECONCILIATION_AT,
    H.LAST_SOURCE_EVENT_AT,
    H.LAST_BRONZE_AT,
    H.LAST_SILVER_AT,
    H.LAST_GOLD_AT,
    H.SOURCE_TO_BRONZE_LATENCY_SECONDS,
    H.BRONZE_TO_SILVER_LATENCY_SECONDS,
    H.SILVER_TO_GOLD_LATENCY_SECONDS,
    H.FRESHNESS_SECONDS,
    H.SLA_STATUS,
    CASE
        WHEN H.HEALTH_REASON IS NULL THEN COALESCE(Q.DQ_REASON, Q.RECONCILIATION_REASON)
        WHEN Q.DQ_REASON IS NULL AND Q.RECONCILIATION_REASON IS NULL THEN H.HEALTH_REASON
        ELSE H.HEALTH_REASON || '; ' || COALESCE(Q.DQ_REASON || '; ', '') || COALESCE(Q.RECONCILIATION_REASON, '')
    END AS HEALTH_REASON,
    COALESCE(I.OPEN_INCIDENT_COUNT, 0) AS OPEN_INCIDENT_COUNT,
    CASE
        WHEN UPPER(D.LIFECYCLE_STATUS) = 'DECOMMISSIONED' THEN 'DECOMMISSIONED'
        WHEN UPPER(D.LIFECYCLE_STATUS) = 'PAUSED' OR D.ENABLED = FALSE THEN 'PAUSED'
        WHEN H.OVERALL_STATUS = 'RED'
          OR Q.DQ_STATUS = 'FAILED'
          OR Q.RECONCILIATION_STATUS = 'FAILED' THEN 'RED'
        WHEN H.OVERALL_STATUS = 'YELLOW'
          OR Q.DQ_STATUS = 'WARNING'
          OR Q.RECONCILIATION_STATUS = 'WARNING' THEN 'YELLOW'
        ELSE H.OVERALL_STATUS
    END AS OVERALL_STATUS
FROM CONTROL.DATASET D
LEFT JOIN CONTROL.DATASET_HEALTH H ON H.DATASET_ID = D.DATASET_ID
LEFT JOIN CONTROL.DATASET_QUALITY_STATUS_V Q ON Q.DATASET_ID = D.DATASET_ID
LEFT JOIN OPEN_INCIDENT I ON I.DATASET_ID = D.DATASET_ID;

