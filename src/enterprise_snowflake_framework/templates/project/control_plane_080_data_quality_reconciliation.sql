-- Normalized data-quality and reconciliation evidence for one domain.
-- Dataset-specific checks remain explicit SQL owned by the dataset implementation.
-- This control-plane migration stores/evaluates results; it is not a generic DQ rule engine.

CREATE TABLE IF NOT EXISTS CONTROL.DQ_RESULT (
    RESULT_ID VARCHAR NOT NULL,
    RUN_ID VARCHAR NOT NULL,
    DATASET_ID VARCHAR NOT NULL,
    VERSION VARCHAR NOT NULL,
    CHECK_ID VARCHAR NOT NULL,
    CHECK_SEVERITY VARCHAR NOT NULL,
    STATUS VARCHAR NOT NULL,
    VIOLATION_COUNT NUMBER(38,0),
    DETAILS VARIANT,
    QUERY_ID VARCHAR,
    CHECKED_AT TIMESTAMP_LTZ NOT NULL,
    CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CONTROL.RECONCILIATION_RESULT (
    RESULT_ID VARCHAR NOT NULL,
    RUN_ID VARCHAR NOT NULL,
    DATASET_ID VARCHAR NOT NULL,
    VERSION VARCHAR,
    STAGE VARCHAR NOT NULL,
    CHECK_ID VARCHAR NOT NULL,
    CHECK_SEVERITY VARCHAR NOT NULL,
    STATUS VARCHAR NOT NULL,
    SOURCE_VALUE VARCHAR,
    TARGET_VALUE VARCHAR,
    DIFFERENCE_VALUE VARCHAR,
    DETAILS VARIANT,
    QUERY_ID VARCHAR,
    CHECKED_AT TIMESTAMP_LTZ NOT NULL,
    CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE PROCEDURE CONTROL.RECORD_DQ_RESULT(
    P_RUN_ID VARCHAR,
    P_DATASET_ID VARCHAR,
    P_VERSION VARCHAR,
    P_CHECK_ID VARCHAR,
    P_CHECK_SEVERITY VARCHAR,
    P_STATUS VARCHAR,
    P_VIOLATION_COUNT NUMBER,
    P_DETAILS VARIANT
)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
    V_RESULT_ID VARCHAR DEFAULT UUID_STRING();
BEGIN
    INSERT INTO CONTROL.DQ_RESULT (
        RESULT_ID, RUN_ID, DATASET_ID, VERSION, CHECK_ID, CHECK_SEVERITY,
        STATUS, VIOLATION_COUNT, DETAILS, QUERY_ID, CHECKED_AT
    ) VALUES (
        :V_RESULT_ID, :P_RUN_ID, :P_DATASET_ID, :P_VERSION, :P_CHECK_ID,
        UPPER(:P_CHECK_SEVERITY), UPPER(:P_STATUS), :P_VIOLATION_COUNT,
        :P_DETAILS, LAST_QUERY_ID(), CURRENT_TIMESTAMP()
    );
    RETURN V_RESULT_ID;
END;
$$;

